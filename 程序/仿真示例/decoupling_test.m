clc;
clear;
close all;

%% ==============================
% 系统稳态增益
% ===============================
K = [0.8 0.4;
     0.3 0.7];

%% ==============================
% 仿真时间
% ===============================
Ts = 1;
t = 0:Ts:2500;
N = length(t);

%% ==============================
% 目标虚拟输入
% ===============================
v1 = zeros(1,N);
v2 = zeros(1,N);

% 100 s 时希望 T1 变化 8，T2 不变化
v1(t >= 100) = 8;
v2(t >= 100) = 0;

%% ==============================
% 情况A：不解耦
% ===============================
u1_no = zeros(1,N);
u2_no = zeros(1,N);

u1_no(t >= 100) = 10;
u2_no(t >= 100) = 0;

%% ==============================
% 情况B：静态解耦
% ===============================
K_inv = inv(K);

u_dec = K_inv * [v1; v2];

u1_dec = u_dec(1,:);
u2_dec = u_dec(2,:);

%% ==============================
% 计算最终温度
% 这里先使用稳态关系
% ===============================

T_no = K * [u1_no; u2_no];

T_dec = K * [u1_dec; u2_dec];

%% ==============================
% 绘图
% ===============================

figure;

subplot(2,1,1);

plot(t,T_no(1,:),'LineWidth',1.5);
hold on;
plot(t,T_dec(1,:),'--','LineWidth',1.5);

grid on;

xlabel('时间 / s');
ylabel('T_1');

title('T_1：解耦前后对比');

legend('不解耦','解耦');

subplot(2,1,2);

plot(t,T_no(2,:),'LineWidth',1.5);
hold on;
plot(t,T_dec(2,:),'--','LineWidth',1.5);

grid on;

xlabel('时间 / s');
ylabel('T_2');

title('T_2：解耦前后对比');

legend('不解耦','解耦');
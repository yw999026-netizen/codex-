%% ========================================================================
% 3. 建立Modbus连接
% ========================================================================

m = [];

simulateMode = forceOfflineMode;


if forceOfflineMode

    fprintf('\n============================================\n');
    fprintf('当前为强制离线模拟模式\n');
    fprintf('不会尝试连接COM端口\n');

%% ========================================================================
% 17. 记录一个标定点或验证点
% ========================================================================

    function recordPointCallback(~,~)

        %% ---------------------------------------------------------------
        % 获取XYZ
        % ---------------------------------------------------------------

        try

            XYZinput = ...
                getXYZInput();

        catch ME

            errordlg( ...
                ME.message, ...
                'XYZ输入错误');

            return;

        end


        %% ---------------------------------------------------------------
        % 获取类型
        % ---------------------------------------------------------------

        typeValue = ...
            get(popupType,'Value');


        if typeValue == 1

            typeName = ...
                '标定点';

        else

            typeName = ...
                '验证点';

        end


        fprintf('\n============================================\n');

        fprintf('准备记录：%s\n', ...
            typeName);

        fprintf('X = %.1f μm\n', ...
            XYZinput(1));

        fprintf('Y = %.1f μm\n', ...
            XYZinput(2));

        fprintf('Z = %.1f μm\n', ...
            XYZinput(3));

        fprintf('============================================\n');


        %% 禁用按钮

        set(btnRecord,'Enable','off');

        set(btnCalculate,'Enable','off');

        set(btnDelete,'Enable','off');

        set(btnClear,'Enable','off');


        %% ===============================================================
        % 第一步：等待5秒
        % ===============================================================

        for remain = settleTimeSec:-1:1

            set(statusText, ...
                'String', ...
                sprintf( ...
                '状态：等待机械稳定，还剩 %d s', ...
                remain));


            drawnow;


            pause(1);

        end


        fprintf('✅ 5秒稳定等待完成。\n');

        fprintf('开始每1秒采集一次，共5个点。\n');


        %% ===============================================================
        % 第二步：正式采5个点
        % ===============================================================

        buffer = ...
            zeros(3,samplesPerPoint);


        measurementClock = ...
            tic;


        for kk = 1:samplesPerPoint

            %% -----------------------------------------------------------
            % 目标采样时间：
            %
            % 1秒
            % 2秒
            % 3秒
            % 4秒
            % 5秒
            %
            % -----------------------------------------------------------

            targetTime = ...
                kk * sampleIntervalSec;


            remainingTime = ...
                targetTime - toc(measurementClock);


            if remainingTime > 0

                pause(remainingTime);

            end


            %% -----------------------------------------------------------
            % 读取探头
            % -----------------------------------------------------------

            try

                probe = ...
                    readProbeOnce(XYZinput);


            catch ME

                restoreButtons();


                errordlg( ...
                    ['读取失败：' ME.message], ...
                    '采集失败');

                return;

            end


            %% -----------------------------------------------------------
            % 检查±100 μm
            % -----------------------------------------------------------

            [OK,message] = ...
                checkProbeRange(probe);


            if ~OK

                restoreButtons();


                errordlg( ...
                    ['本次数据无效：' message], ...
                    '探头超范围');

                return;

            end


            %% 保存

            buffer(:,kk) = ...
                probe;


            lastProbe = ...
                probe;


            updateProbeDisplay(probe);


            %% GUI

            set(statusText, ...
                'String', ...
                sprintf( ...
                '状态：采样 %d / %d，时间 %d s', ...
                kk, ...
                samplesPerPoint, ...
                kk*sampleIntervalSec));


            %% 控制台

            fprintf( ...
                ['第 %d/%d 点 | ' ...
                 'P1=%8.3f  ' ...
                 'P2=%8.3f  ' ...
                 'P3=%8.3f μm\n'], ...
                kk, ...
                samplesPerPoint, ...
                probe(1), ...
                probe(2), ...
                probe(3));


            drawnow;

        end


        %% ===============================================================
        % 第三步：计算5个点的平均值
        % ===============================================================

        probeMean = ...
            mean(buffer,2);


        %% ===============================================================
        % 第四步：计算标准差
        % ===============================================================

        probeStd = ...
            std(buffer,0,2);


        %% ===============================================================
        % 第五步：保存当前标定位置
        % ===============================================================

        pointNumber = ...
            pointNumber + 1;


        pointType(end+1) = ...
            typeValue;


        commandXYZ(:,end+1) = ...
            XYZinput;


        probeMeanData(:,end+1) = ...
            probeMean;


        probeStdData(:,end+1) = ...
            probeStd;


        recordTime{end+1} = ...
            datestr( ...
            now, ...
            'yyyy-mm-dd HH:MM:SS');


        %% 更新GUI

        refreshTable();


        set(countText, ...
            'String', ...
            sprintf( ...
            '已记录：%d 个点', ...
            pointNumber));


        set(statusText, ...
            'String', ...
            sprintf( ...
            '状态：第%d个%s记录完成', ...
            pointNumber, ...
            typeName));


        %% 控制台

        fprintf('\n--------------------------------------------\n');

        fprintf('✅ 当前位置测量完成\n');


        fprintf('\n5点平均值：\n');

        fprintf('P1平均 = %.4f μm\n', ...
            probeMean(1));

        fprintf('P2平均 = %.4f μm\n', ...
            probeMean(2));

        fprintf('P3平均 = %.4f μm\n', ...
            probeMean(3));


        fprintf('\n5点标准差：\n');

        fprintf('P1标准差 = %.4f μm\n', ...
            probeStd(1));

        fprintf('P2标准差 = %.4f μm\n', ...
            probeStd(2));

        fprintf('P3标准差 = %.4f μm\n', ...
            probeStd(3));


        fprintf('--------------------------------------------\n');


        %% 恢复按钮

        restoreButtons();

    end



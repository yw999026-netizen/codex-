%% ========================================================================
% 19. 计算XYZ标定矩阵
% ========================================================================

    function calculateCalibrationCallback(~,~)

        %% ---------------------------------------------------------------
        % 获取所有标定点
        % ---------------------------------------------------------------

        calibrationIndex = ...
            pointType == 1;


        validationIndex = ...
            pointType == 2;


        numberCalibration = ...
            sum(calibrationIndex);


        if numberCalibration < 4

            errordlg( ...
                ['标定点数量不足。' ...
                 '必须覆盖X、Y、Z三个方向。'], ...
                '无法计算');

            return;

        end


        XYZcal = ...
            commandXYZ(:,calibrationIndex)';


        ProbeCal = ...
            probeMeanData(:,calibrationIndex)';


        %% ===============================================================
        % 找零点
        % ===============================================================

        zeroIndex = ...
            abs(XYZcal(:,1)) < 1e-9 & ...
            abs(XYZcal(:,2)) < 1e-9 & ...
            abs(XYZcal(:,3)) < 1e-9;


        if ~any(zeroIndex)

            errordlg( ...
                ['没有找到 X=0、Y=0、Z=0 的标定点。' ...
                 '请至少记录一个零位。'], ...
                '缺少标定零点');

            return;

        end


        %% ---------------------------------------------------------------
        % 如果有多个零点，自动取平均
        % ---------------------------------------------------------------

        Probe0 = ...
            mean( ...
            ProbeCal(zeroIndex,:), ...
            1);


        fprintf('\n============================================\n');

        fprintf('三探头标定零位平均值\n');

        fprintf('============================================\n');

        fprintf('Probe1零位 = %.4f μm\n', ...
            Probe0(1));

        fprintf('Probe2零位 = %.4f μm\n', ...
            Probe0(2));

        fprintf('Probe3零位 = %.4f μm\n', ...
            Probe0(3));


        %% ===============================================================
        % 转成相对探头变化量
        % ===============================================================

        dProbeCal = ...
            ProbeCal - Probe0;


        % 用户输入本身已经是相对于零位的XYZ
        dXYZCal = ...
            XYZcal;


        %% ===============================================================
        % 检查是否覆盖3个独立方向
        % ===============================================================

        if rank(dProbeCal) < 3

            errordlg( ...
                ['标定数据没有覆盖三个独立方向。' ...
                 '必须分别进行X、Y、Z方向移动。'], ...
                '标定数据不足');

            return;

        end


        %% ===============================================================
        % 最小二乘求标定矩阵
        %
        % dXYZ = dProbe * M
        %
        % MATLAB：
        %
        % M = dProbe \ dXYZ
        %
        % 正式程序使用列向量：
        %
        % XYZ = C_xyz_from_probe * dProbe
        %
        % 因此：
        %
        % C_xyz_from_probe = M'
        %
        % ===============================================================

        M = ...
            dProbeCal \ dXYZCal;


        C_xyz_from_probe = ...
            M';


        %% ===============================================================
        % 用标定数据重新预测
        % ===============================================================

        XYZcalPred = ...
            ( ...
            C_xyz_from_probe * ...
            dProbeCal' ...
            )';


        %% ===============================================================
        % 标定残差
        % ===============================================================

        errorCal = ...
            XYZcalPred - ...
            dXYZCal;


        %% RMSE

        RMSE = ...
            sqrt( ...
            mean( ...
            errorCal.^2, ...
            1));


        %% MAE

        MAE = ...
            mean( ...
            abs(errorCal), ...
            1);


        %% 最大绝对误差

        MAXE = ...
            max( ...
            abs(errorCal), ...
            [], ...
            1);


        %% ===============================================================
        % 条件数
        % ===============================================================

        matrixCondition = ...
            cond(C_xyz_from_probe);


        %% ===============================================================
        % 独立验证
        % ===============================================================


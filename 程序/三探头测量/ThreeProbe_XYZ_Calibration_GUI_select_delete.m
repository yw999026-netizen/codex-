% 25. 探头范围检查
% ========================================================================

    function [OK,message] = checkProbeRange(probe)

        OK = true;

        message = '';


        for ii = 1:3

            if ~isfinite(probe(ii))

                OK = false;

                message = ...
                    sprintf( ...
                    '探头%d数据无效', ...
                    ii);

                return;

            end


            if abs(probe(ii)) > ...
                    probeLimit_um

                OK = false;


                message = ...
                    sprintf( ...
                    ['探头%d当前值 %.2f μm，' ...
                     '已经超出±%d μm有效范围'], ...
                    ii, ...
                    probe(ii), ...
                    probeLimit_um);

                return;

            end

        end

    end



%% ========================================================================
% 23. 读取一次探头
% ========================================================================

    function probe = readProbeOnce(XYZinput)

        %% ===============================================================
        % 离线模拟模式
        % ===============================================================

        if simulateMode

            % XYZ = C * dProbe
            %
            % 所以：
            %
            % dProbe = C \ XYZ

            dProbe = ...
                C_demo_true \ ...
                XYZinput;


            % 加一点随机测量噪声

            probe = ...
                probeDemoZero + ...
                dProbe + ...
                [ ...
                0.12; ...
                0.10; ...
                0.14 ...
                ] .* ...
                randn(3,1);


            return;

        end


        %% ===============================================================
        % 真实Modbus
        % ===============================================================

        probe = ...
            zeros(3,1);


        for jj = 1:numProbes

            raw = read( ...
                m, ...
                'holdingregs', ...
                probeSensors(jj).reg, ...
                1, ...
                probeSensors(jj).id);


            rawSigned = ...
                signed16ToDouble(raw);


            probe(jj) = ...
                rawSigned * ...
                probeSensors(jj).scale;

        end

    end


%% ========================================================================
% 24. Modbus 16位有符号转换
% ========================================================================

    function value = signed16ToDouble(raw)

        value = ...
            double(raw);


        if value > 32767

            value = ...
                value - 65536;

        end

    end



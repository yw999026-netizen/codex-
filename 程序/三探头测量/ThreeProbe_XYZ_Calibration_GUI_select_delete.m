    function deleteSelectedCallback(~,~)

        if pointNumber == 0
            errordlg('当前没有可删除的数据点。','无法删除');
            return;
        end

        if isempty(selectedTableRow) || ...
                selectedTableRow < 1 || ...
                selectedTableRow > pointNumber

            errordlg( ...
                '请先在下方表格中单击选择要删除的那一行。', ...
                '请选择数据点');
            return;
        end

        deleteIndex = selectedTableRow;

        if pointType(deleteIndex) == 1
            typeName = '标定点';
        else
            typeName = '验证点';
        end

        XYZdelete = commandXYZ(:,deleteIndex);

        message = sprintf( ...
            ['确定删除第 %d 个点吗？\n\n' ...
             '类型：%s\n' ...
             'X = %.1f μm\n' ...
             'Y = %.1f μm\n' ...
             'Z = %.1f μm'], ...
            deleteIndex, ...
            typeName, ...
            XYZdelete(1), ...
            XYZdelete(2), ...
            XYZdelete(3));

        answer = questdlg( ...
            message, ...
            '确认删除', ...
            '删除', ...
            '取消', ...
            '取消');

        if ~strcmp(answer,'删除')
            return;
        end

        % 删除对应编号的数据，所有数组必须同步删除
        pointType(deleteIndex) = [];
        commandXYZ(:,deleteIndex) = [];
        probeMeanData(:,deleteIndex) = [];
        probeStdData(:,deleteIndex) = [];
        recordTime(deleteIndex) = [];

        pointNumber = pointNumber - 1;

        % 删除后清除当前选择，避免再次误删
        selectedTableRow = [];

        refreshTable();

        set(countText, ...
            'String', ...
            sprintf('已记录：%d 个点',pointNumber));

        set(statusText, ...
            'String', ...
            sprintf('状态：已删除原第 %d 个点，剩余数据已自动重新编号', ...
            deleteIndex));

    end



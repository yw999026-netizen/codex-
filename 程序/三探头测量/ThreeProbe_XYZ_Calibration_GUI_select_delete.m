        fprintf('探头2地址：%d\n',probeSensors(2).id);
        fprintf('探头3地址：%d\n',probeSensors(3).id);


    catch ME

        if autoFallbackOffline

            fprintf('\n⚠️ 真实设备连接失败：\n');
            fprintf('%s\n',ME.message);

            fprintf('\n自动进入离线模拟模式。\n');


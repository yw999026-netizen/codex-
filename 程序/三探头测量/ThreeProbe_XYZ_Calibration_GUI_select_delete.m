    function tableSelectionCallback(~,event)

        % event.Indices 的第一列是行号，第二列是列号
        if isempty(event.Indices)
            selectedTableRow = [];
            return;
        end

        % 如果一次选中了多个单元格，只取第一行
        selectedTableRow = event.Indices(1,1);

        set(statusText, ...
            'String', ...
            sprintf('状态：已选择第 %d 个点，可点击“删除选中点”', ...
